const safeGet = k => { try { return localStorage.getItem(k); } catch { return null; } };
const safeSet = (k, v) => { try { localStorage.setItem(k, v); } catch {} };

function setLang(lang) {
  document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = i18n[lang][el.dataset.i18n];
  });
  document.getElementById("lang").textContent = lang === "pt" ? "EN" : "PT";
  safeSet("lang", lang);
}

function setTheme(theme) {
  document.documentElement.dataset.theme = theme;
  safeSet("theme", theme);
}

let lang = safeGet("lang") || (navigator.language.startsWith("pt") ? "pt" : "en");
setLang(lang);
setTheme(safeGet("theme") ||
  (matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light"));

document.getElementById("lang").onclick = () => { lang = lang === "pt" ? "en" : "pt"; setLang(lang); };
document.getElementById("theme").onclick = () =>
  setTheme(document.documentElement.dataset.theme === "dark" ? "light" : "dark");
document.getElementById("year").textContent = new Date().getFullYear();
